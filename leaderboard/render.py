"""Static-HTML leaderboard renderer.

Reads ``scoring_out/leaderboard.json`` and emits a single self-contained
``index.html`` rendering the (condition × model × composition) matrix.

Usage::

    python -m leaderboard.render \\
        --leaderboard scoring_out/leaderboard.json \\
        --delta scoring_out/composition_delta.csv \\
        --out leaderboard/_site/
"""

from __future__ import annotations

import argparse
import csv
import html
import json
from collections import defaultdict
from pathlib import Path
from typing import Any


def render_html(*, leaderboard: dict[str, Any], deltas: list[dict[str, str]]) -> str:
    """Render the leaderboard + delta tables into a single HTML page."""
    cells = leaderboard.get("cells", [])
    n_total = leaderboard.get("n_runs_total", 0)
    conditions = sorted({c["condition_code"] for c in cells})
    models = sorted({c["model_id"] for c in cells})

    # Index by (condition, model, composition) for the matrix render.
    indexed: dict[tuple[str, str, str], dict[str, Any]] = {
        (c["condition_code"], c["model_id"], c["composition"]): c for c in cells
    }

    parts: list[str] = []
    parts.append("<!DOCTYPE html><html lang='en'><head><meta charset='utf-8'>")
    parts.append("<title>udm-bench leaderboard</title>")
    parts.append("<style>")
    parts.append(_STYLE)
    parts.append("</style></head><body>")
    parts.append("<h1>udm-bench leaderboard</h1>")
    parts.append(f"<p>Total runs: <strong>{n_total}</strong></p>")
    parts.append("<h2>Root-cause accuracy by (condition × model × composition)</h2>")
    parts.append(
        _render_matrix(indexed, conditions, models, metric="root_cause_accuracy", fmt="{:.2%}")
    )
    parts.append("<h2>Cross-vendor attribution accuracy (multi-vendor only)</h2>")
    parts.append(
        _render_matrix(
            indexed,
            conditions,
            models,
            metric="cross_vendor_attribution_accuracy",
            fmt="{:.2%}",
            compositions=("multi-vendor",),
        )
    )
    parts.append("<h2>Mean USD cost per run</h2>")
    parts.append(_render_matrix(indexed, conditions, models, metric="usd_cost_mean", fmt="${:.4f}"))
    parts.append("<h2>Same-vs-multi-vendor delta (multi − single)</h2>")
    parts.append(_render_delta_table(deltas))
    parts.append(
        "<footer><p>Generated by <code>leaderboard.render</code>. "
        "Headline result: the multi-vendor − single-vendor delta per "
        "(condition, model). Smaller deltas for UDM-MCP conditions "
        "support the benchmark hypothesis.</p></footer>"
    )
    parts.append("</body></html>")
    return "".join(parts)


def _render_matrix(
    indexed: dict[tuple[str, str, str], dict[str, Any]],
    conditions: list[str],
    models: list[str],
    *,
    metric: str,
    fmt: str,
    compositions: tuple[str, ...] = ("single-vendor", "multi-vendor"),
) -> str:
    out: list[str] = ["<table class='matrix'><thead><tr>"]
    out.append("<th>condition</th><th>composition</th>")
    for m in models:
        out.append(f"<th>{html.escape(m)}</th>")
    out.append("</tr></thead><tbody>")
    for cond in conditions:
        for comp in compositions:
            out.append(f"<tr><td><strong>{html.escape(cond)}</strong></td>")
            out.append(f"<td>{html.escape(comp)}</td>")
            for m in models:
                cell = indexed.get((cond, m, comp))
                val = cell.get(metric) if cell else None
                if val is None:
                    out.append("<td class='na'>—</td>")
                else:
                    out.append(f"<td>{html.escape(fmt.format(val))}</td>")
            out.append("</tr>")
    out.append("</tbody></table>")
    return "".join(out)


def _render_delta_table(deltas: list[dict[str, str]]) -> str:
    if not deltas:
        return "<p><em>No delta rows yet — need both single- and multi-vendor runs per (condition, model).</em></p>"
    grouped: dict[tuple[str, str], list[dict[str, str]]] = defaultdict(list)
    for d in deltas:
        grouped[(d["condition_code"], d["model_id"])].append(d)
    out: list[str] = ["<table class='deltas'><thead><tr>"]
    out.append("<th>condition</th><th>model</th><th>metric</th>")
    out.append("<th>single</th><th>multi</th><th>Δ (multi−single)</th>")
    out.append("<th>n(single)</th><th>n(multi)</th></tr></thead><tbody>")
    for (cond, model), rows in sorted(grouped.items()):
        for r in rows:
            out.append("<tr>")
            out.append(f"<td>{html.escape(cond)}</td>")
            out.append(f"<td>{html.escape(model)}</td>")
            out.append(f"<td>{html.escape(r['metric'])}</td>")
            out.append(f"<td>{html.escape(str(r['single_vendor_value']))}</td>")
            out.append(f"<td>{html.escape(str(r['multi_vendor_value']))}</td>")
            out.append(f"<td>{html.escape(str(r['delta']))}</td>")
            out.append(f"<td>{html.escape(str(r['single_vendor_n']))}</td>")
            out.append(f"<td>{html.escape(str(r['multi_vendor_n']))}</td>")
            out.append("</tr>")
    out.append("</tbody></table>")
    return "".join(out)


_STYLE = """
body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif; max-width: 1100px; margin: 2rem auto; padding: 0 1rem; color: #1a1a1a; }
h1, h2 { color: #0b3d91; }
table { border-collapse: collapse; width: 100%; margin: 1rem 0 2rem; }
th, td { border: 1px solid #ccd; padding: 0.4rem 0.7rem; text-align: right; font-variant-numeric: tabular-nums; }
th { background: #eef; text-align: center; }
td:first-child, td:nth-child(2) { text-align: left; }
.na { color: #999; text-align: center; }
footer { margin-top: 3rem; color: #555; font-size: 0.9rem; }
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render udm-bench static leaderboard")
    parser.add_argument("--leaderboard", required=True, type=Path, help="path to leaderboard.json")
    parser.add_argument("--delta", required=True, type=Path, help="path to composition_delta.csv")
    parser.add_argument("--out", required=True, type=Path, help="output directory")
    args = parser.parse_args(argv)

    with args.leaderboard.open("r", encoding="utf-8") as f:
        lb = json.load(f)
    with args.delta.open("r", encoding="utf-8", newline="") as f:
        deltas = list(csv.DictReader(f))

    html_str = render_html(leaderboard=lb, deltas=deltas)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "index.html").write_text(html_str, encoding="utf-8")
    print(f"wrote {args.out / 'index.html'}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
