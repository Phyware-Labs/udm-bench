def per_fault_figure(runs: list[dict], ev: dict[str, dict]) -> str:
    """Heatmap: share of each fault's missions found, per (model, condition).

    Rows are faults (evidence-bearing first), columns are cells; the ``evidence``
    column shows how many of the fault's missions carry a visible signal.
    """
    faults = sorted(
        {e["fault_id"] for e in ev.values()},
        key=lambda f: (
            -sum(e["detectable"] for e in ev.values() if e["fault_id"] == f)
            / sum(1 for e in ev.values() if e["fault_id"] == f),
            f,
        ),
    )
    cols = [(m, c) for m in MODELS for c in MAIN_CONDS]
    cells = {mc: _cell(runs, *mc) for mc in cols}
    w, h = 0.9, 0.42
    lines = list(_STANDALONE_HEAD)
    for j, (_m, c) in enumerate(cols):
        x = (j + 1) * w + 0.25 * (j >= len(MAIN_CONDS))
        lines.append(
            f"\\node[anchor=south] at ({x + w / 2:.2f},{h * len(faults) + 0.05:.2f}) {{{c}}};"
        )
    for k, m in enumerate(MODELS):
        x0 = (1 + k * len(MAIN_CONDS)) * w + 0.25 * k
        xc = x0 + w * len(MAIN_CONDS) / 2
        lines.append(
            f"\\node[anchor=south] at ({xc:.2f},{h * len(faults) + 0.4:.2f}) "
            f"{{\\texttt{{{MODEL_LABEL[m]}}}}};"
        )
    lines.append(
        f"\\node[anchor=south] at ({w / 2:.2f},{h * len(faults) + 0.05:.2f}) {{evidence}};"
    )
    for i, f in enumerate(faults):
        y = h * (len(faults) - 1 - i)
        mids = [mid for mid, e in ev.items() if e["fault_id"] == f]
        n, k = len(mids), sum(ev[mid]["detectable"] for mid in mids)
        lines.append(
            f"\\node[anchor=east] at (-0.05,{y + h / 2:.2f}) "
            f"{{\\texttt{{{f.replace('_', chr(92) + '_')}}}}};"
        )
        shade = round(100 * k / n)
        lines.append(f"\\fill[black!{shade // 4}] (0,{y:.2f}) rectangle ({w:.2f},{y + h:.2f});")
        lines.append(f"\\node at ({w / 2:.2f},{y + h / 2:.2f}) {{{k}/{n}}};")
        for j, mc in enumerate(cols):
            x = (j + 1) * w + 0.25 * (j >= len(MAIN_CONDS))
            found = sum(_correct(cells[mc][mid]) for mid in mids)
            shade = round(70 * found / n)
            text = "white" if shade > 40 else "black"
            lines.append(
                f"\\fill[blue!{shade}!white] ({x:.2f},{y:.2f}) rectangle ({x + w:.2f},{y + h:.2f});"
            )
            lines.append(
                f"\\node[text={text}] at ({x + w / 2:.2f},{y + h / 2:.2f}) {{{found}/{n}}};"
            )
        lines.append(
            f"\\draw[white, line width=0.6pt] (0,{y:.2f}) -- "
            f"({(len(cols) + 1) * w + 0.25:.2f},{y:.2f});"
        )
    return "\n".join(lines + _STANDALONE_TAIL)


def paired_forest_figure(runs: list[dict]) -> str:
    """Forest plot: paired-bootstrap recall difference for each comparison."""
    rows: list[tuple[str, Any]] = []
    for model in MODELS:
        for x, y in COMPARISONS:
            cx, cy = _cell(runs, model, x), _cell(runs, model, y)
            mids = sorted(cx)
            d = paired_bootstrap_diff(
                [float(_correct(cx[m])) for m in mids],
                [float(_correct(cy[m])) for m in mids],
                [_stratum(cx[m]) for m in mids],
                recall_stat,
            )
            rows.append((f"{MODEL_LABEL[model]}: {x} vs {y}", d))
    n = len(rows)
    lines = list(_STANDALONE_HEAD) + [
        "\\begin{axis}[",
        "  width=8cm, height=7cm, xmin=-0.3, xmax=0.8,",
        f"  ymin=-0.7, ymax={n - 0.3}, ytick={{{','.join(str(i) for i in range(n))}}},",
        "  yticklabels={" + ",".join(r[0] for r in reversed(rows)) + "},",
        "  xlabel={Recall difference (first $-$ second), paired 95\\% CI},",
        "  tick label style={font=\\scriptsize}, label style={font=\\scriptsize},",
        "  xmajorgrids, major grid style={draw=black!12}, axis line style={black!55},",
        "]",
        f"\\draw[black!50, dashed] (axis cs:0,-0.7) -- (axis cs:0,{n - 0.3});",
    ]
    for i, (_, d) in enumerate(reversed(rows)):
        color = "blue!65!black" if d.excludes_zero() else "black!45"
        lines.append(
            f"\\draw[{color}, thick] (axis cs:{d.lo:.3f},{i}) -- (axis cs:{d.hi:.3f},{i});"
        )
        lines.append(f"\\fill[{color}] (axis cs:{d.point:.3f},{i}) circle (1.8pt);")
    lines.append("\\end{axis}")
    return "\n".join(lines + _STANDALONE_TAIL)


