# --------------------------------------------------------------------------- io


def load() -> tuple[list[dict], dict[str, dict]]:
    with (_DATA_DIR / "runs.jsonl").open(encoding="utf-8") as fh:
        runs = [json.loads(line) for line in fh if line.strip()]
    missions = json.loads((_DATA_DIR / "missions.json").read_text(encoding="utf-8"))
    return runs, missions


class Report:
    """Accumulates markdown sections and mirrors each table to a CSV."""

    def __init__(self) -> None:
        self.parts: list[str] = [
            "<!-- AUTO-GENERATED by `python -m analysis.results` — do not edit by hand. -->",
            "# Phase 4 analysis tables",
            "",
        ]

    def heading(self, text: str, note: str = "") -> None:
        self.parts += [f"## {text}", ""]
        if note:
            self.parts += [note, ""]

    def table(self, name: str, header: list[str], rows: list[list[Any]]) -> None:
        self.parts.append("| " + " | ".join(header) + " |")
        self.parts.append("|" + "|".join("---" for _ in header) + "|")
        for r in rows:
            self.parts.append("| " + " | ".join(str(x) for x in r) + " |")
        self.parts.append("")
        with (_OUT_DIR / f"{name}.csv").open("w", encoding="utf-8", newline="") as fh:
            w = csv.writer(fh)
            w.writerow(header)
            w.writerows(rows)

    def write(self) -> None:
        (_OUT_DIR / "tables.md").write_text("\n".join(self.parts), encoding="utf-8")


# ---------------------------------------------------------------------- helpers


def _fmt_ci(ci: Any) -> str:
    return "--" if ci is None else f"{ci.point:.2f} [{ci.lo:.2f}, {ci.hi:.2f}]"


def _fmt_diff(d: Any) -> str:
    mark = "*" if d.excludes_zero() else ""
    return f"{d.point:+.2f} [{d.lo:+.2f}, {d.hi:+.2f}]{mark}"


def _fmt_p(p: float) -> str:
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def _cell(runs: list[dict], model: str, cond: str) -> dict[str, dict]:
    """mission_id -> run for one (model, condition)."""
    return {
        r["mission_id"]: r for r in runs if r["model_id"] == model and r["condition_code"] == cond
    }


def _correct(r: dict) -> bool:
    return r["root_cause_correct"] is True


def _stratum(r: dict) -> str:
    return "clean" if r["is_clean_mission"] else "faulty"


