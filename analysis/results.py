def evidence_section(rep: Report, missions: dict[str, dict], ev: dict[str, dict]) -> None:
    rep.heading(
        "1. Evidence ceiling",
        "Fault-aware oracle over the shared 2 Hz `telemetry.sqlite` (`analysis/evidence.py`). "
        "A fault is *detectable* when the statistic its mechanism should move exceeds the "
        "maximum over every clean mission of the same composition. Upper bound on evidence, "
        "not a fair detector.",
    )
    rows = []
    for mid in sorted(ev, key=lambda m: (ev[m]["fault_id"], m)):
        e = ev[mid]
        val = "--" if not math.isfinite(e["value"]) else f"{e['value']:.3f}"
        margin = "--" if not math.isfinite(e["margin"]) else f"{e['margin']:.2f}x"
        rows.append(
            [
                e["fault_id"],
                missions[mid]["composition"],
                mid.rsplit("-", 1)[1],
                e["statistic"],
                val,
                f"{e['clean_max']:.3f}",
                margin,
                "yes" if e["detectable"] else "no",
                e["reason"],
            ]
        )
    rep.table(
        "evidence_by_mission",
        [
            "fault",
            "composition",
            "mission",
            "statistic",
            "value",
            "clean max",
            "margin",
            "detectable",
            "reason",
        ],
        rows,
    )
    by_fault: dict[str, list[bool]] = defaultdict(list)
    for e in ev.values():
        by_fault[e["fault_id"]].append(e["detectable"])
    rows = [[f, FAULT_SIGNAL[f][1], f"{sum(v)}/{len(v)}"] for f, v in sorted(by_fault.items())]
    total = [d for v in by_fault.values() for d in v]
    rows.append(["**all**", "", f"**{sum(total)}/{len(total)}**"])
    rep.table("evidence_by_fault", ["fault", "signal checked", "detectable"], rows)


def matrix_section(rep: Report, runs: list[dict]) -> None:
    rep.heading(
        "2. Full matrix (model x condition x composition)",
        "Rates carry percentile-bootstrap 95% CIs (`scoring.stats`). Vendor attribution is "
        "on multi-vendor faulty missions. $/found = total spend / faults found.",
    )
    rows = []
    for model in MODELS:
        conds = MAIN_CONDS + (["D", "E"] if model == "azure-gpt-5-mini" else [])
        for cond in conds:
            cell = list(_cell(runs, model, cond).values())
            for comp in COMPOSITIONS + ["all"]:
                rs = [r for r in cell if comp == "all" or r["composition"] == comp]
                fc = [r["root_cause_correct"] for r in rs if not r["is_clean_mission"]]
                cc = [r["root_cause_correct"] for r in rs if r["is_clean_mission"]]
                st = cell_stats(fc, cc)
                bd = st.breakdown
                xv = [
                    r["cross_vendor_attribution_correct"] is True
                    for r in rs
                    if r["composition"] == "multi-vendor" and not r["is_clean_mission"]
                ]
                spend = sum(r["usd_cost"] for r in rs)
                rows.append(
                    [
                        MODEL_LABEL[model],
                        COND_LABEL[cond],
                        comp,
                        len(rs),
                        f"{bd.found}/{bd.n_faulty}",
                        f"{bd.false_alarm}/{bd.n_clean}",
                        _fmt_ci(st.recall_ci),
                        _fmt_ci(st.specificity_ci),
                        _fmt_ci(st.balanced_ci),
                        f"{sum(xv)}/{len(xv)}" if xv else "--",
                        f"{sum(r['hallucination_total'] for r in rs) / len(rs):.2f}",
                        f"{spend / len(rs):.3f}",
                        f"{spend / bd.found:.2f}" if bd.found else "--",
                        f"{sum(r['tool_call_count'] for r in rs) / len(rs):.1f}",
                    ]
                )
    rep.table(
        "matrix",
        [
            "model",
            "condition",
            "composition",
            "n",
            "found",
            "false alarms",
            "recall",
            "specificity",
            "balanced",
            "vendor attr.",
            "halluc./run",
            "$/run",
            "$/found",
            "tools/run",
        ],
        rows,
    )


def per_fault_section(rep: Report, runs: list[dict], ev: dict[str, dict]) -> None:
    rep.heading(
        "3. Detection by fault",
        "Faults found per (model, condition). `evidence` = missions where the oracle sees "
        "the fault's signal.",
    )
    faults = sorted({e["fault_id"] for e in ev.values()})
    cols = [(m, c) for m in MODELS for c in MAIN_CONDS]
    cells = {mc: _cell(runs, *mc) for mc in cols}
    rows = []
    for f in faults:
        mids = [m for m, e in ev.items() if e["fault_id"] == f]
        row: list[Any] = [f, len(mids), sum(ev[m]["detectable"] for m in mids)]
        for mc in cols:
            row.append(sum(_correct(cells[mc][m]) for m in mids))
        rows.append(row)
    header = ["fault", "n", "evidence"] + [f"{MODEL_LABEL[m]} {c}" for m, c in cols]
    rep.table("per_fault", header, rows)


def _paired_rows(
    runs: list[dict], model: str, pairs: list[tuple[str, str]], subset: set[str] | None = None
) -> list[list[Any]]:
    """Paired tests for each (x, y) pair; Holm-adjusted within each metric family."""
    metrics: list[tuple[str, Any]] = [
        ("faults found", lambda r: not r["is_clean_mission"]),
        ("correct abstain", lambda r: r["is_clean_mission"]),
        (
            "vendor attribution",
            lambda r: r["composition"] == "multi-vendor" and not r["is_clean_mission"],
        ),
    ]
    out: list[list[Any]] = []
    for metric, keep in metrics:
        family: list[list[Any]] = []
        pvals: list[float] = []
        for x, y in pairs:
            cx, cy = _cell(runs, model, x), _cell(runs, model, y)
            mids = sorted(
                m
                for m, r in cx.items()
                if keep(r) and (subset is None or m in subset or r["is_clean_mission"])
            )
            if metric == "vendor attribution":
                xs = [cx[m]["cross_vendor_attribution_correct"] is True for m in mids]
                ys = [cy[m]["cross_vendor_attribution_correct"] is True for m in mids]
            else:
                xs = [_correct(cx[m]) for m in mids]
                ys = [_correct(cy[m]) for m in mids]
            if not mids:
                continue
            mc = mcnemar_exact(xs, ys)
            px, py = sum(xs) / len(xs), sum(ys) / len(ys)
            family.append(
                [
                    MODEL_LABEL[model],
                    f"{x} vs {y}",
                    metric,
                    f"{sum(xs)}/{len(xs)}",
                    f"{sum(ys)}/{len(ys)}",
                    mc.b,
                    mc.c,
                    _fmt_p(mc.p),
                    None,
                    f"{cohens_h(px, py):+.2f}",
                ]
            )
            pvals.append(mc.p)
        for row, adj in zip(family, holm(pvals), strict=True):
            row[8] = _fmt_p(adj)
        out += family
    return out


def paired_section(rep: Report, runs: list[dict]) -> None:
    rep.heading(
        "4. Paired tests (same missions, condition vs condition)",
        "Exact McNemar on discordant missions: `b` = only the first condition right, `c` = "
        "only the second. Holm adjustment is within each (model, metric) family of five "
        "comparisons. Cohen's h: ~0.2 small, ~0.5 medium, ~0.8 large.",
    )
    rows: list[list[Any]] = []
    for model in MODELS:
        rows += _paired_rows(runs, model, COMPARISONS)
    rep.table(
        "paired_mcnemar",
        ["model", "pair", "metric", "first", "second", "b", "c", "p", "p (Holm)", "h"],
        rows,
    )

    rep.parts += [
        "Paired-bootstrap 95% CIs on the difference (first minus second); `*` = CI excludes 0.",
        "",
    ]
    rows = []
    for model in MODELS:
        for x, y in COMPARISONS:
            cx, cy = _cell(runs, model, x), _cell(runs, model, y)
            mids = sorted(cx)
            xs = [float(_correct(cx[m])) for m in mids]
            ys = [float(_correct(cy[m])) for m in mids]
            strata = [_stratum(cx[m]) for m in mids]
            rows.append(
                [
                    MODEL_LABEL[model],
                    f"{x} vs {y}",
                    _fmt_diff(paired_bootstrap_diff(xs, ys, strata, recall_stat)),
                    _fmt_diff(paired_bootstrap_diff(xs, ys, strata, balanced_stat)),
                ]
            )
    rep.table("paired_bootstrap", ["model", "pair", "recall diff", "balanced diff"], rows)


def evidence_restricted_section(rep: Report, runs: list[dict], ev: dict[str, dict]) -> None:
    detectable = {m for m, e in ev.items() if e["detectable"]}
    n = len(detectable)
    rep.heading(
        "5. Detection restricted to evidence-bearing faults",
        f"Only the {n} faulty missions whose fault the oracle can see; clean missions unchanged.",
    )
    rows = []
    for model in MODELS:
        for cond in MAIN_CONDS:
            cell = _cell(runs, model, cond)
            fc = [cell[m]["root_cause_correct"] for m in sorted(detectable)]
            cc = [r["root_cause_correct"] for r in cell.values() if r["is_clean_mission"]]
            st = cell_stats(fc, cc)
            rows.append(
                [
                    MODEL_LABEL[model],
                    COND_LABEL[cond],
                    f"{st.breakdown.found}/{n}",
                    _fmt_ci(st.recall_ci),
                    _fmt_ci(st.balanced_ci),
                ]
            )
    rep.table("evidence_restricted", ["model", "condition", "found", "recall", "balanced"], rows)
    rows = []
    for model in MODELS:
        rows += [
            r for r in _paired_rows(runs, model, COMPARISONS, detectable) if r[2] == "faults found"
        ]
    rep.table(
        "evidence_restricted_mcnemar",
        ["model", "pair", "metric", "first", "second", "b", "c", "p", "p (Holm)", "h"],
        rows,
    )


def delta_section(rep: Report, runs: list[dict], ev: dict[str, dict]) -> None:
    rep.heading(
        "6. Multi-vendor delta",
        "Recall on multi-vendor minus single-vendor faulty missions. CIs resample each "
        "composition independently. h compares the two recalls. The two sets do not share a "
        "fault mix (section 3), so the all-faults delta is confounded; the TB3-faults row "
        "keeps only TurtleBot3 faults on both sides.",
    )
    subsets = {
        "all faults": None,
        "TB3 faults only": {m for m, e in ev.items() if e["fault_id"].startswith("tb3_")},
        "evidence-bearing only": {m for m, e in ev.items() if e["detectable"]},
    }
    rows = []
    vectors: dict[tuple[str, str, str], tuple[list[str], list[float], list[str]]] = {}
    for label, subset in subsets.items():
        for model in MODELS:
            for cond in MAIN_CONDS:
                cell = _cell(runs, model, cond)
                mids = sorted(
                    m
                    for m, r in cell.items()
                    if not r["is_clean_mission"] and (subset is None or m in subset)
                )
                vals = [float(_correct(cell[m])) for m in mids]
                comps = [cell[m]["composition"] for m in mids]
                vectors[(label, model, cond)] = (mids, vals, comps)
                s = [v for v, c in zip(vals, comps, strict=True) if c == "single-vendor"]
                mv = [v for v, c in zip(vals, comps, strict=True) if c == "multi-vendor"]
                ps, pm = sum(s) / len(s), sum(mv) / len(mv)
                d = stratified_bootstrap(vals, comps, composition_delta_stat)
                rows.append(
                    [
                        label,
                        MODEL_LABEL[model],
                        COND_LABEL[cond],
                        f"{ps:.2f} ({int(sum(s))}/{len(s)})",
                        f"{pm:.2f} ({int(sum(mv))}/{len(mv)})",
                        _fmt_diff(d),
                        f"{cohens_h(pm, ps):+.2f}",
                    ]
                )
    rep.table(
        "composition_delta",
        ["fault set", "model", "condition", "single recall", "multi recall", "delta [95% CI]", "h"],
        rows,
    )
    rep.parts += [
        "Difference in delta, C minus each baseline: missions resampled within composition "
        "and shared by both conditions (paired). Negative = C's delta is smaller.",
        "",
    ]
    rows = []
    for label in subsets:
        for model in MODELS:
            _, vc, comps = vectors[(label, model, "C")]
            for base in ("A", "B", "G"):
                _, vb, _ = vectors[(label, model, base)]
                d = paired_bootstrap_diff(vc, vb, comps, composition_delta_stat)
                rows.append([label, MODEL_LABEL[model], f"C vs {base}", _fmt_diff(d)])
    rep.table("delta_difference", ["fault set", "model", "pair", "delta_C - delta_base"], rows)


def ablation_section(rep: Report, runs: list[dict]) -> None:
    rep.heading(
        "7. Ablations at gpt-5-mini (C vs D / E / G)",
        "Same v4 batch as C/G. D drops `correlate_events`, E drops `compliance_audit`, G "
        "drops `health_scan`. F (introspection-only) exists only from an earlier harness "
        "version and is not comparable; it is excluded.",
    )
    rows = _paired_rows(runs, "azure-gpt-5-mini", ABLATIONS)
    rep.table(
        "ablation_mcnemar",
        ["model", "pair", "metric", "first", "second", "b", "c", "p", "p (Holm)", "h"],
        rows,
    )


def hallucination_section(rep: Report, runs: list[dict]) -> None:
    rep.heading(
        "8. Hallucination and vendor misattribution",
        "Hallucinations per run (fabricated event ids / field paths / standards, "
        "`scoring/hallucination.py`) by composition, and wrong-vendor attributions on "
        "multi-vendor faulty missions.",
    )
    rows = []
    for model in MODELS:
        for cond in MAIN_CONDS:
            cell = list(_cell(runs, model, cond).values())
            by = {
                comp: [r["hallucination_total"] for r in cell if r["composition"] == comp]
                for comp in COMPOSITIONS
            }
            mv_faulty = [
                r for r in cell if r["composition"] == "multi-vendor" and not r["is_clean_mission"]
            ]
            hs = sum(by["single-vendor"]) / len(by["single-vendor"])
            hm = sum(by["multi-vendor"]) / len(by["multi-vendor"])
            rows.append(
                [
                    MODEL_LABEL[model],
                    COND_LABEL[cond],
                    f"{hs:.2f}",
                    f"{hm:.2f}",
                    f"{hm - hs:+.2f}",
                    f"{sum(r['vendor_misattribution'] for r in mv_faulty)}/{len(mv_faulty)}",
                ]
            )
    rep.table(
        "hallucination",
        ["model", "condition", "single", "multi", "delta", "wrong vendor"],
        rows,
    )


def _failure_kind(r: dict, ev: dict[str, dict], missions: dict[str, dict]) -> str:
    if not r["submitted_diagnosis"] or not r["submitted_fault_id"]:
        return "no diagnosis"
    if r["submitted_fault_id"] == "no_fault":
        return "said no_fault"
    truth_vendors = {f["vendor"] for f in missions[r["mission_id"]]["faults"]}
    if r["composition"] == "multi-vendor" and r["submitted_vendor"] not in truth_vendors:
        return "wrong vendor"
    return "right vendor, wrong fault"


def taxonomy_section(
    rep: Report, runs: list[dict], missions: dict[str, dict], ev: dict[str, dict]
) -> None:
    rep.heading(
        "9. Failure taxonomy",
        "Every missed faulty run, by what the agent submitted, split by whether the oracle "
        "sees the fault's evidence. Rule-based from the submitted diagnosis; no trace "
        "reading.",
    )
    kinds = ["no diagnosis", "said no_fault", "wrong vendor", "right vendor, wrong fault"]
    rows = []
    for model in MODELS:
        for cond in MAIN_CONDS:
            for comp in COMPOSITIONS:
                cell = [
                    r
                    for r in _cell(runs, model, cond).values()
                    if r["composition"] == comp and not r["is_clean_mission"] and not _correct(r)
                ]
                for has_ev in (True, False):
                    sub = [r for r in cell if ev[r["mission_id"]]["detectable"] is has_ev]
                    c = Counter(_failure_kind(r, ev, missions) for r in sub)
                    rows.append(
                        [
                            MODEL_LABEL[model],
                            COND_LABEL[cond],
                            comp,
                            "yes" if has_ev else "no",
                            len(sub),
                        ]
                        + [c.get(k, 0) for k in kinds]
                    )
    rep.table(
        "failure_taxonomy",
        ["model", "condition", "composition", "evidence", "missed"] + kinds,
        rows,
    )

    rep.parts += ["Most-claimed faults on clean missions (false alarms).", ""]
    rows = []
    for model in MODELS:
        for cond in MAIN_CONDS:
            fa = [
                r["submitted_fault_id"]
                for r in _cell(runs, model, cond).values()
                if r["is_clean_mission"] and not _correct(r)
            ]
            top = ", ".join(f"{f} ({n})" for f, n in Counter(fa).most_common(3))
            rows.append([MODEL_LABEL[model], COND_LABEL[cond], len(fa), top or "--"])
    rep.table("false_alarm_claims", ["model", "condition", "false alarms", "top claims"], rows)


