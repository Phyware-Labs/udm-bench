"""Phase 4 results analysis: every table behind ``analysis/*.md``.

Reads only the committed snapshot in ``analysis/data/`` (see
:mod:`analysis.extract`) and writes ``analysis/out/tables.md`` plus one CSV per
table. Nothing in the written analysis is transcribed by hand.

Sections:

1. Evidence ceiling — which injected faults are visible in the recording.
2. Full matrix — (model x condition x composition) with every metric.
3. Per-fault detection.
4. Paired tests — condition vs condition on the same missions (exact McNemar,
   Holm-adjusted, Cohen's h, paired-bootstrap CIs).
5. Detection restricted to evidence-bearing faults.
6. Multi-vendor delta with CIs and effect sizes, and difference-in-delta tests.
7. Ablations (gpt-5-mini): C vs D / E / G.
8. Hallucination and vendor misattribution.
9. Failure taxonomy for missed faults and false alarms.

Usage::

    python -m analysis.results
"""

