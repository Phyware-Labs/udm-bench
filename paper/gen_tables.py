#!/usr/bin/env python3
"""Generate LaTeX result tables directly from the scoring outputs.

The paper never hand-copies numbers. This reads the scored ``scorecards.jsonl``
files (produced by ``python -m scoring.score``) and emits ``.tex`` table
fragments under ``paper/tables/``. Re-running keeps every number, CI, and count
in the paper in lock-step with the underlying runs.

Cells are pulled from the canonical scoring directories:

* mini A/B      <- scoring_results_phase4        (baselines, matched 2 Hz)
* mini C/G      <- scoring_results_phase4_v4      (UDM + health_scan ablation)
* gpt-5 A/B     <- scoring_results_phase4_gpt5_ab (full-n strong-model baselines)
* gpt-5 C/G     <- scoring_results_phase4_gpt5_cg (strong-model UDM ablation)

Usage::

    python paper/gen_tables.py            # writes paper/tables/*.tex
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

# Make the repo root importable so we can reuse scoring.stats (single source of
# truth for the breakdown + bootstrap CI math the paper reports).
_REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_REPO_ROOT))

from analysis.evidence import assess  # noqa: E402
from analysis.paired import (  # noqa: E402
    paired_bootstrap_diff,
    recall_stat,
)
from analysis.results import (  # noqa: E402
    COMPARISONS,
    MODELS,
    _cell,
    _correct,
    _paired_rows,
    _stratum,
)
from analysis.results import load as load_analysis  # noqa: E402
from scoring.stats import cell_stats  # noqa: E402

_TABLES_DIR = Path(__file__).resolve().parent / "tables"
_FIGURES_DIR = Path(__file__).resolve().parent / "figures"

# (condition, scoring_dir) sources per model tier.
_SOURCES: dict[str, dict[str, str]] = {
    "azure-gpt-5-mini": {
        "A": "scoring_results_phase4",
        "B": "scoring_results_phase4",
        "G": "scoring_results_phase4_v4",
        "C": "scoring_results_phase4_v4",
    },
    "azure-gpt-5": {
        "A": "scoring_results_phase4_gpt5_ab",
        "B": "scoring_results_phase4_gpt5_ab",
        "G": "scoring_results_phase4_gpt5_cg",
        "C": "scoring_results_phase4_gpt5_cg",
    },
}

# Display label per condition, in report order (baselines first, then UDM).
_COND_LABEL: dict[str, str] = {
    "A": "A: raw bag (text)",
    "B": "B: generic SQL",
    "G": "G: UDM$-$health\\_scan",
    "C": "C: UDM$+$health\\_scan",
}
_COND_ORDER = ["A", "B", "G", "C"]


def _load_scorecards(scoring_dir: str) -> list[dict]:
    path = _REPO_ROOT / scoring_dir / "scorecards.jsonl"
    if not path.exists():
        raise FileNotFoundError(f"missing scorecards: {path} (run scoring.score first)")
    with path.open(encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def _cell_rows(model_id: str, condition: str) -> tuple[list, list, list, list]:
    """Return (faulty_correct, clean_correct, costs, tool_counts) for one cell."""
    cards = _load_scorecards(_SOURCES[model_id][condition])
    fc, cc, costs, tools = [], [], [], []
    for c in cards:
        if c.get("condition_code") != condition or c.get("model_id") != model_id:
            continue
        if c.get("is_clean_mission"):
            cc.append(c.get("root_cause_correct"))
        else:
            fc.append(c.get("root_cause_correct"))
        costs.append(float(c.get("usd_cost", 0.0) or 0.0))
        tools.append(int(c.get("tool_call_count", 0) or 0))
    return fc, cc, costs, tools


def _ci(cival) -> str:
    if cival is None:
        return "--"
    return f"{cival.point:.2f} [{cival.lo:.2f}, {cival.hi:.2f}]"


def _detection_table(model_id: str, caption: str, label: str) -> str:
    lines = [
        "% AUTO-GENERATED by paper/gen_tables.py — do not edit by hand.",
        "\\begin{table*}[t]",
        "\\centering",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        "\\small",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{lccccccr}",
        "\\toprule",
        "Condition & Found/Faulty & Recall [95\\% CI] & Specificity [95\\% CI] & "
        "Balanced [95\\% CI] & FA & Tools & \\$/run \\\\",
        "\\midrule",
    ]
    for cond in _COND_ORDER:
        fc, cc, costs, tools = _cell_rows(model_id, cond)
        st = cell_stats(fc, cc)
        bd = st.breakdown
        cost = sum(costs) / len(costs) if costs else 0.0
        tool = sum(tools) / len(tools) if tools else 0.0
        lines.append(
            f"{_COND_LABEL[cond]} & "
            f"{bd.found}/{bd.n_faulty} & "
            f"{_ci(st.recall_ci)} & "
            f"{_ci(st.specificity_ci)} & "
            f"{_ci(st.balanced_ci)} & "
            f"{bd.false_alarm} & "
            f"{tool:.1f} & "
            f"{cost:.3f} \\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabular}%",
        "}",
        "\\end{table*}",
        "",
    ]
    return "\n".join(lines)


def _cross_vendor_counts(model_id: str, condition: str) -> tuple[int, int, int]:
    """Return (correct_vendor, fault_found, n) on multi-vendor faulty missions."""
    cards = _load_scorecards(_SOURCES[model_id][condition])
    mv = [
        c
        for c in cards
        if c.get("condition_code") == condition
        and c.get("model_id") == model_id
        and c.get("composition") == "multi-vendor"
        and not c.get("is_clean_mission")
    ]
    xok = sum(1 for c in mv if c.get("cross_vendor_attribution_correct") is True)
    found = sum(1 for c in mv if c.get("root_cause_correct") is True)
    return xok, found, len(mv)


def _cross_vendor_table() -> str:
    """Correct-vendor attribution on multi-vendor faulty missions, both scales.

    The clean cross-vendor metric: on missions where two vendors run in one
    world, did the agent blame the *right* platform? (Unlike the composition
    delta, this is not confounded by the single-vs-multi fault mix.)
    """
    lines = [
        "% AUTO-GENERATED by paper/gen_tables.py — do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Cross-vendor attribution on multi-vendor faulty missions "
        "($n{=}13$ per cell): did the agent blame the correct platform (TurtleBot3 "
        "vs.\\ PX4)? Reported at both model scales.}",
        "\\label{tab:cross-vendor}",
        "\\footnotesize",
        "\\resizebox{\\columnwidth}{!}{%",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        " & \\multicolumn{2}{c}{gpt-5} & \\multicolumn{2}{c}{gpt-5-mini} \\\\",
        "\\cmidrule(lr){2-3} \\cmidrule(lr){4-5}",
        "Condition & Vendor & Found & Vendor & Found \\\\",
        "\\midrule",
    ]
    for cond in _COND_ORDER:
        bx, bf, bn = _cross_vendor_counts("azure-gpt-5", cond)
        mx, mf, mn = _cross_vendor_counts("azure-gpt-5-mini", cond)
        lines.append(f"{_COND_LABEL[cond]} & {bx}/{bn} & {bf}/{bn} & {mx}/{mn} & {mf}/{mn} \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}%",
        "}",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


def _detection_scatter_figure() -> str:
    """Faults found vs. false alarms, both scales, against the chance diagonal.

    Balanced accuracy exceeds 0.5 exactly when ``found/n_faulty >
    false_alarm/n_clean``, so the line ``y = (n_faulty/n_clean) x`` is the
    chance frontier: points above it beat a coin flip, points below do not.
    Drawing it makes the abstention artifact and the response-bias shift legible
    in one picture.
    """
    series: dict[str, list[tuple[str, int, int]]] = {}
    n_faulty = n_clean = 0
    for model_id in ("azure-gpt-5", "azure-gpt-5-mini"):
        pts = []
        for cond in _COND_ORDER:
            fc, cc, _, _ = _cell_rows(model_id, cond)
            bd = cell_stats(fc, cc).breakdown
            pts.append((cond, bd.false_alarm, bd.found))
            n_faulty, n_clean = bd.n_faulty, bd.n_clean
        series[model_id] = pts

    def _coords(model_id: str) -> str:
        return " ".join(f"({fa},{found})" for _, fa, found in series[model_id])

    def _labels(model_id: str, anchor: str) -> list[str]:
        return [
            f"\\node[{anchor}, font=\\scriptsize] at (axis cs:{fa},{found}) {{{cond}}};"
            for cond, fa, found in series[model_id]
        ]

    ymax = n_faulty // 2 + 3
    chance_y = ymax - 3
    chance_x = round(chance_y * n_clean / n_faulty)

    lines = [
        "% AUTO-GENERATED by paper/gen_tables.py — do not edit by hand.",
        "\\begin{figure}[t]",
        "\\centering",
        "\\begin{tikzpicture}",
        "\\begin{axis}[",
        "  width=1.02\\columnwidth, height=0.80\\columnwidth,",
        f"  xlabel={{False alarms (of {n_clean} clean missions)}},",
        f"  ylabel={{Faults found (of {n_faulty} faulty)}},",
        f"  xmin=-1.2, xmax={n_clean + 1}, ymin=-1.2, ymax={ymax},",
        "  grid=both,",
        "  major grid style={line width=0.1pt, draw=black!12},",
        "  tick label style={font=\\scriptsize},",
        "  label style={font=\\scriptsize},",
        "  legend style={font=\\scriptsize, at={(0.98,0.98)}, anchor=north east,",
        "                draw=black!30, fill=white, row sep=-1pt},",
        "  legend cell align=left,",
        "  axis line style={black!55},",
        "]",
        f"\\addplot[domain=0:{n_clean}, samples=2, dashed, black!45, thick,",
        f"         forget plot] {{{n_faulty}/{n_clean}*x}};",
        "\\node[font=\\scriptsize\\itshape, text=black!55, anchor=north west]",
        f"  at (axis cs:{chance_x},{chance_y}) {{chance}};",
        "\\addplot[only marks, mark=*, mark size=2.6pt, draw=blue!65!black,",
        f"         fill=blue!65!black] coordinates {{{_coords('azure-gpt-5')}}};",
        "\\addlegendentry{gpt-5}",
        "\\addplot[only marks, mark=o, mark size=2.6pt, draw=black!60,",
        f"         line width=0.7pt] coordinates {{{_coords('azure-gpt-5-mini')}}};",
        "\\addlegendentry{gpt-5-mini}",
    ]
    lines += _labels("azure-gpt-5", "above right=0.5mm and 0.8mm")
    lines += _labels("azure-gpt-5-mini", "below right=0.5mm and 0.8mm")
    lines += [
        "\\end{axis}",
        "\\end{tikzpicture}",
        "\\caption{Faults found vs.\\ false alarms, both model scales. The dashed "
        "line is the chance frontier (balanced accuracy $=0.5$): a condition beats "
        "a coin flip only above it. Exactly one point clears it---the full UDM "
        "surface at \\texttt{gpt-5}. \\condB{} hugs the origin by abstaining; "
        "\\condA{} and \\condC{} at \\texttt{gpt-5-mini} sit far right by "
        "over-alarming.}",
        "\\label{fig:detection-scatter}",
        "\\end{figure}",
        "",
    ]
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Tables built from the paired / evidence analysis (``analysis/``). They read
# the committed snapshot in ``analysis/data/`` and reuse the same functions that
# write ``analysis/out/tables.md``, so the paper and the analysis cannot drift.
# ---------------------------------------------------------------------------

_HEAD = "% AUTO-GENERATED by paper/gen_tables.py — do not edit by hand."


def _tt(name: str) -> str:
    return "\\texttt{" + name.replace("_", "\\_") + "}"


def _per_fault_table(runs: list[dict], ev: dict[str, dict]) -> str:
    """Faults found per fault type and cell, beside the evidence ceiling."""
    faults = sorted(
        {e["fault_id"] for e in ev.values()},
        key=lambda f: (
            -sum(e["detectable"] for e in ev.values() if e["fault_id"] == f)
            / sum(1 for e in ev.values() if e["fault_id"] == f),
            f,
        ),
    )
    cols = [(m, c) for m in MODELS for c in _COND_ORDER]
    cells = {mc: _cell(runs, *mc) for mc in cols}
    lines = [
        _HEAD,
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Faults found by fault type. \\emph{Evid.}\\ counts the missions on which "
        "a fault-aware oracle sees the fault's signal in the recording (above every clean "
        "mission of the same composition). No condition at either scale found a fault "
        "the oracle could not see.}",
        "\\label{tab:per-fault}",
        "\\small",
        "\\begin{tabular}{lcc" + "c" * len(cols) + "}",
        "\\toprule",
        " & & & \\multicolumn{4}{c}{gpt-5} & \\multicolumn{4}{c}{gpt-5-mini} \\\\",
        "\\cmidrule(lr){4-7} \\cmidrule(lr){8-11}",
        "Fault & $n$ & Evid. & " + " & ".join(c for _, c in cols) + " \\\\",
        "\\midrule",
    ]
    tot_n = tot_k = 0
    totals = [0] * len(cols)
    for f in faults:
        mids = [m for m, e in ev.items() if e["fault_id"] == f]
        n, k = len(mids), sum(ev[m]["detectable"] for m in mids)
        tot_n, tot_k = tot_n + n, tot_k + k
        found = [sum(_correct(cells[mc][m]) for m in mids) for mc in cols]
        totals = [a + b for a, b in zip(totals, found, strict=True)]
        lines.append(f"{_tt(f)} & {n} & {k} & " + " & ".join(map(str, found)) + " \\\\")
    lines += [
        "\\midrule",
        f"All & {tot_n} & {tot_k} & " + " & ".join(map(str, totals)) + " \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table*}",
        "",
    ]
    return "\n".join(lines)


def _evidence_restricted_table(runs: list[dict], ev: dict[str, dict]) -> str:
    """Detection on evidence-bearing faulty missions only (clean missions unchanged)."""
    detectable = sorted(m for m, e in ev.items() if e["detectable"])
    n = len(detectable)
    lines = [
        _HEAD,
        "\\begin{table}[t]",
        "\\centering",
        f"\\caption{{Detection on the {n} faulty missions whose fault leaves evidence, "
        "with all 24 clean missions. Balanced accuracy with bootstrap 95\\% CI.}",
        "\\label{tab:evidence-restricted}",
        "\\footnotesize",
        "\\resizebox{\\columnwidth}{!}{%",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        " & \\multicolumn{2}{c}{gpt-5} & \\multicolumn{2}{c}{gpt-5-mini} \\\\",
        "\\cmidrule(lr){2-3} \\cmidrule(lr){4-5}",
        "Condition & Found & Balanced & Found & Balanced \\\\",
        "\\midrule",
    ]
    for cond in _COND_ORDER:
        cells = []
        for model in MODELS:
            cell = _cell(runs, model, cond)
            fc = [cell[m]["root_cause_correct"] for m in detectable]
            cc = [r["root_cause_correct"] for r in cell.values() if r["is_clean_mission"]]
            st = cell_stats(fc, cc)
            cells.append(f"{st.breakdown.found}/{n} & {_ci(st.balanced_ci)}")
        lines.append(f"{_COND_LABEL[cond]} & " + " & ".join(cells) + " \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}%",
        "}",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


def _p(p: str) -> str:
    """Compact p-value for a dense cell: ``0.039`` -> ``.039``."""
    if p == "<0.001":
        return "$<$.001"
    return p[1:] if p.startswith("0.") else p


def _paired_table(runs: list[dict]) -> str:
    """Paired comparisons: McNemar discordant splits (Holm p) and paired recall CIs."""
    metrics = ["faults found", "correct abstain", "vendor attribution"]
    by_key: dict[tuple[str, str, str], list] = {}
    for model in MODELS:
        for row in _paired_rows(runs, model, COMPARISONS):
            by_key[(model, row[1], row[2])] = row
    lines = [
        _HEAD,
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Paired comparisons on the same missions. Each McNemar cell is the "
        "discordant split $b$--$c$ ($b$: only the first condition correct; $c$: only the "
        "second) with the exact $p$, Holm-adjusted over the five comparisons in its "
        "(model, metric) family. Found: $23$ faulty missions; Abstain: $24$ clean; "
        "Vendor: $13$ multi-vendor faulty. $\\Delta$Recall is the paired-bootstrap "
        "difference with 95\\% CI; bold marks Holm $p<0.05$ or a CI excluding $0$.}",
        "\\label{tab:paired}",
        "\\small",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{l" + "cccc" * len(MODELS) + "}",
        "\\toprule",
        " & \\multicolumn{4}{c}{gpt-5} & \\multicolumn{4}{c}{gpt-5-mini} \\\\",
        "\\cmidrule(lr){2-5} \\cmidrule(lr){6-9}",
        "Pair & Found & Abstain & Vendor & $\\Delta$Recall [95\\% CI] & "
        "Found & Abstain & Vendor & $\\Delta$Recall [95\\% CI] \\\\",
        "\\midrule",
    ]
    for x, y in COMPARISONS:
        cells = []
        for model in MODELS:
            for metric in metrics:
                row = by_key[(model, f"{x} vs {y}", metric)]
                b, c, holm_p = row[5], row[6], row[8]
                text = f"{b}--{c} ({_p(holm_p)})"
                sig = holm_p == "<0.001" or float(holm_p) < 0.05
                cells.append(f"\\textbf{{{text}}}" if sig else text)
            cx, cy = _cell(runs, model, x), _cell(runs, model, y)
            mids = sorted(cx)
            d = paired_bootstrap_diff(
                [float(_correct(cx[m])) for m in mids],
                [float(_correct(cy[m])) for m in mids],
                [_stratum(cx[m]) for m in mids],
                recall_stat,
            )
            text = f"{d.point:+.2f} [{d.lo:+.2f}, {d.hi:+.2f}]".replace("-", "$-$")
            cells.append(f"\\textbf{{{text}}}" if d.excludes_zero() else text)
        lines.append(f"{x} vs {y} & " + " & ".join(cells) + " \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}%",
        "}",
        "\\end{table*}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    _TABLES_DIR.mkdir(parents=True, exist_ok=True)
    _FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    outputs = {
        "detection_gpt5.tex": _detection_table(
            "azure-gpt-5",
            "Detection breakdown at \\texttt{gpt-5} ($n{=}47$: 23 faulty, 24 clean). "
            "Conditions ordered by faults \\emph{found}. FA = false alarms on clean "
            "missions. Bracketed ranges are percentile bootstrap 95\\% CIs.",
            "tab:detection-gpt5",
        ),
        "detection_mini.tex": _detection_table(
            "azure-gpt-5-mini",
            "Detection breakdown at \\texttt{gpt-5-mini} ($n{=}47$). Same layout as "
            "Table~\\ref{tab:detection-gpt5}. At this scale $B$'s abstention inflates "
            "the balanced scalar while it finds no faults, and no condition exceeds "
            "chance (balanced $=0.5$).",
            "tab:detection-mini",
        ),
        "cross_vendor.tex": _cross_vendor_table(),
    }
    runs, missions = load_analysis()
    ev = assess(missions)
    outputs["per_fault.tex"] = _per_fault_table(runs, ev)
    outputs["evidence_restricted.tex"] = _evidence_restricted_table(runs, ev)
    outputs["paired.tex"] = _paired_table(runs)
    for name, content in outputs.items():
        (_TABLES_DIR / name).write_text(content, encoding="utf-8")
        print(f"wrote paper/tables/{name}")
    (_FIGURES_DIR / "detection_scatter.tex").write_text(
        _detection_scatter_figure(), encoding="utf-8"
    )
    print("wrote paper/figures/detection_scatter.tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
